function kernel = kernelFunctionNEW(kernel)

switch kernel.type
    case 'gaussian'
        kernel = @(x1,x2) kernel.scale * exp(-norm(x1-x2)^2/(kernel.std));
        
    case 'gaussian_A'
        kernel = @(x1,x2) kernel.scale * exp(-norm(x1(1:3)-x2(1:3))^2/kernel.std)*min(exp(kernel.alt*x1(4)),exp(kernel.alt*x2(4)));
%     case 'altitude'
%         kernel = @(x1,x2) max(exp(kernel.alt*x1(4)),exp(kernel.alt*x2(4)));
    case 'PeriodicP'
        kernel = @(x1,x2) kernel.scale^2*exp(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2);
    case 'PeriodicTP2'
        kernel = @(x1,x2) kernel.scale^2 -(2*(kernel.scale*pi*kernel.frequency*abs(x1-x2))^2/kernel.std^2 )...
        *exp(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)*cos(2*pi*kernel.frequency*abs(x1-x2));
    case 'exponentialTP1'
        kernel = @(x1,x2) kernel.scale*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2));
    case 'exponentialTP2'
        kernel = @(x1,x2) kernel.scale^2*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^2/2);
    case 'exponentialTP3'
        kernel = @(x1,x2) kernel.scale^2*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^2/2....
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^3/6);
    case 'exponentialTP4'
        kernel = @(x1,x2) kernel.scale*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2))*exp(-abs(x1-x2)/kernel.std);
%     case 'exponentialTP4'
%         kernel = @(x1,x2) kernel.scale*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2*kernel.c_t))*exp(-abs(x1-x2)/kernel.std);
%         
    case 'exponentialTP5'
        kernel = @(x1,x2) kernel.scale*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2)^2/2)*exp(-abs(x1-x2)/kernel.std);
        
    case 'periodic+exponential2'
        kernel = @(x1,x2) kernel.scale*((1/kernel.c_t^2-1/kernel.c_t^4)*cos(2*pi*kernel.frequency*abs(x1-x2))...
            +1/4*kernel.c_t^4*cos(4*pi*kernel.frequency*abs(x1-x2))...
            +(1-1/kernel.c_t^2+3/(4*kernel.c_t^4)))*exp(-abs(x1-x2)/kernel.std);
        
    case 'exponentialTP6'
        kernel = @(x1,x2) kernel.scale*(1 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2)^2/2 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.c_t^2)^3/6)*exp(-abs(x1-x2)/kernel.std);
        
    case 'periodic+exponential3'
        kernel = @(x1,x2) kernel.scale*((1/kernel.c_t^2-1/kernel.c_t^4+15/24*kernel.c_t^6)*cos(2*pi*kernel.frequency*abs(x1-x2))...
            +(1/4*kernel.c_t^4-1/4*kernel.c_t^6)*cos(4*pi*kernel.frequency*abs(x1-x2))...
            +(1/24*kernel.c_t^6)*cos(6*pi*kernel.frequency*abs(x1-x2))...
            +(1-1/kernel.c_t^2+3/(4*kernel.c_t^4)-5/12*kernel.c_t^6))*exp(-abs(x1-x2)/kernel.std);       
  
    case 'periodic+exponential4'
        kernel = @(x1,x2) kernel.scale*(kernel.c_t-kernel.c_t^2+5*kernel.c_t^3/8-7*kernel.c_t^4/24)*cos(2*pi*kernel.frequency*abs(x1-x2))...
            +(kernel.c_t^2/4-kernel.c_t^3/4+7*kernel.c_t^4/48)*cos(4*pi*kernel.frequency*abs(x1-x2))...
            +(kernel.c_t^3/24-kernel.c_t^4/24)*cos(6*pi*kernel.frequency*abs(x1-x2))...
            +(kernel.c_t^4/192)*cos(8*pi*kernel.frequency*abs(x1-x2))...
            +(1-kernel.c_t+3*kernel.c_t^2/4-5*kernel.c_t^3/12+35*kernel.c_t^4/192)*exp(-abs(x1-x2)/kernel.std); 
    case 'periodic+exponential5'
        kernel = @(x1,x2) kernel.scale*((1/kernel.c_t^2-1/kernel.c_t^4+15/24*kernel.c_t^6)*cos(2*pi*kernel.frequency*abs(x1-x2))...
            +(1/4*kernel.c_t^4-1/4*kernel.c_t^6)*cos(4*pi*kernel.frequency*abs(x1-x2))...
            +(1/24*kernel.c_t^6)*cos(6*pi*kernel.frequency*abs(x1-x2))...
            +(1-1/kernel.c_t^2+3/(4*kernel.c_t^4)-5/12*kernel.c_t^6))*exp(-abs(x1-x2)/kernel.std);
    case 'periodic+exponential6'
        kernel = @(x1,x2) kernel.scale*((1/kernel.c_t^2-1/kernel.c_t^4+15/24*kernel.c_t^6)*cos(2*pi*kernel.frequency*abs(x1-x2))...
            +(1/4*kernel.c_t^4-1/4*kernel.c_t^6)*cos(4*pi*kernel.frequency*abs(x1-x2))...
            +(1/24*kernel.c_t^6)*cos(6*pi*kernel.frequency*abs(x1-x2))...
            +(1-1/kernel.c_t^2+3/(4*kernel.c_t^4)-5/12*kernel.c_t^6))*exp(-abs(x1-x2)/kernel.std);
    case 'exponentialTP7'
        kernel = @(x1,x2) kernel.scale*(1 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^2/2 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^3/6 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^4/24);
     case 'exponentialTP8'
        kernel = @(x1,x2) kernel.scale*(1 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^2/2 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^3/6 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^4/24 ...
            +(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)^5/120);
    
    case 'exponentialTP'
        kernel = @(x1,x2) kernel.alpha*kernel.scale^2*2*(sin(pi*abs(x1-x2)*kernel.frequency))^2;

   
    case 'periodic+exponential1'
        kernel = @(x1,x2) kernel.scale*(1/kernel.c_t^2*cos(2*pi*kernel.frequency*abs(x1-x2))*exp(-abs(x1-x2)/kernel.std)...
            +(1-1/kernel.c_t^2)*exp(-abs(x1-x2)/kernel.std));

        
    case 'PeriodicExponential'
        kernel = @(x1,x2) kernel.scale*(kernel.c_t*cos(2*pi*kernel.frequency*abs(x1-x2))*exp(-abs(x1-x2)/kernel.std^2)...
            +(1-kernel.c_t)*exp(-abs(x1-x2)/kernel.std^2));
      
        
    case'LocallyPer'
%         kernel = @(x1,x2) kernel.scale*cos(2*pi*kernel.frequency*x1)*cos(2*pi*kernel.frequency*x2)*exp(-abs(x1-x2)/kernel.std);
        kernel = @(x1,x2) kernel.scale^2*exp(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2)*exp(-norm(x1-x2)^2/(2*kernel.std^2));
    case 'exponential'
        kernel = @(x1,x2) kernel.scale*exp(-norm(x1-x2)/kernel.std);
    case 'periodic'
        kernel = @(x1,x2) kernel.scale*cos(2*pi*kernel.frequency*(abs(x1-x2)))*exp(-abs(x1-x2)/kernel.std);
    case 'periodic4'
%         kernel = @(x1,x2) kernel.scale*(sin(2*pi*kernel.frequency*(abs(x1-x2)))+1)*exp(-abs(x1-x2)/kernel.std);
         kernel = @(x1,x2) kernel.scale^2*(1+(-2*(sin(pi*abs(x1-x2)*kernel.frequency))^2/kernel.std^2))*exp(-abs(x1-x2)/kernel.std^2);
        kernel = @(x1,x2) kernel.scale^2/kernel.std^2*cos(2*pi*kernel.frequency*(abs(x1-x2)))*exp(-abs(x1-x2)/kernel.std^2)...
            +kernel.scale^2*(1-1/kernel.std^2)*exp(-abs(x1-x2)/kernel.std^2);
    case 'periodic2'
        kernel = @(x1,x2) kernel.scale*min(exp(cos(2*pi*kernel.frequency*x1)),exp(cos(2*pi*kernel.frequency*x2)));
    case 'periodic3'
        kernel = @(x1,x2) kernel.scale*cos(2*pi*kernel.frequency*(abs(x1-x2)));
    case 'DC'
        kernel = @(x1,x2) kernel.scale*kernel.rho^abs(x1-x2);
        
    case 'Matern'
        lambda = sqrt(3)/kernel.l;
        kernel = @(x1,x2) (1+lambda*abs(x1-x2))*exp(-lambda*abs(x1-x2));
end
end

